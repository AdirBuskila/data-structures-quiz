def opts(*vals):
    return [{"id": IDS[i], "type": "text", "value": v} for i, v in enumerate(vals)]


def rub(*items):
    return [{"text": t, "points": p} for t, p in items]


def add(num, part, **kw):
    for q in questions:
        if q["num"] == num and q.get("part") == part:
            q.update(kw)
            return
    raise KeyError((num, part))


def ch(prompt, options, explain):
    """choice step; the FIRST option is the correct one (the UI shuffles)."""
    return {"type": "choice", "prompt": prompt, "options": opts(*options), "correctId": "a", "explain": explain}


def num_(prompt, answer, explain, tol=0):
    return {"type": "numeric", "prompt": prompt, "answer": answer, "tol": tol, "explain": explain}


def txt(prompt, accept, explain):
    return {"type": "text", "prompt": prompt, "accept": accept, "normalize": "complexity", "explain": explain}


